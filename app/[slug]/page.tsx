import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import {
  getProperties,
  getProperty,
  getPropertySlugs,
} from "@/lib/sanity/properties";
import { site } from "@/lib/site";
import { generalEnquiryLink } from "@/lib/whatsapp";
import SiteHeader from "@/components/SiteHeader";
import SiteFooter from "@/components/SiteFooter";
import Hero from "@/components/Hero";
import Gallery from "@/components/Gallery";
import UnitCard from "@/components/UnitCard";
import VisitOptions from "@/components/VisitOptions";
import WhatsAppButton from "@/components/WhatsAppButton";
import StickyEnquire from "@/components/StickyEnquire";
import Reveal from "@/components/Reveal";
import CurrencyNote from "@/components/CurrencyNote";
import PropertyCard from "@/components/PropertyCard";

type Params = { slug: string };

// Pre-render every property at build time (SSG) for Vercel.
// Re-check Sanity for edits every 5 minutes without a redeploy.
export const revalidate = 300;

export async function generateStaticParams(): Promise<Params[]> {
  const slugs = await getPropertySlugs();
  return slugs.map((slug) => ({ slug }));
}

export async function generateMetadata({
  params,
}: {
  params: Params;
}): Promise<Metadata> {
  const property = await getProperty(params.slug);
  if (!property) return {};

  const title = `${property.name} — ${property.location}`;
  const description = property.tagline;
  const url = `${site.url}/${property.slug}`;
  // Static per-property OG card generated by `npm run generate-og`.
  const ogImage = `/og/${property.slug}.png`;

  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      type: "website",
      title: `${property.name} · ${site.name}`,
      description,
      url,
      images: [{ url: ogImage, width: 1200, height: 630, alt: property.name }],
    },
    twitter: {
      card: "summary_large_image",
      title: `${property.name} · ${site.name}`,
      description,
      images: [ogImage],
    },
  };
}

function SectionTitle({
  eyebrow,
  title,
  intro,
}: {
  eyebrow: string;
  title: string;
  intro?: string;
}) {
  return (
    <Reveal>
      <p className="eyebrow">{eyebrow}</p>
      <h2 className="h-fluid-2 mt-3">{title}</h2>
      {intro && (
        <p className="mt-3 max-w-2xl text-[clamp(1rem,2.2vw,1.125rem)] text-muted">
          {intro}
        </p>
      )}
    </Reveal>
  );
}

export default async function PropertyPage({
  params,
}: {
  params: Params;
}) {
  const property = await getProperty(params.slug);

  // Unknown slugs and not-yet-launched properties have no public page.
  if (!property || property.status !== "live") {
    notFound();
  }

  const enquireHref = generalEnquiryLink(property);
  // Other properties to surface as a "keep exploring" cross-link (drives a
  // second pageview, which is what actually moves bounce rate).
  const all = await getProperties();
  const others = all.filter((p) => p.slug !== property.slug);

  return (
    <>
      <SiteHeader overlay />
      <Hero
        media={property.hero}
        name={property.name}
        tagline={property.tagline}
        location={property.location}
      />

      <main className="pb-28">
        {/* Gallery first — lead with visuals, not text (esp. on mobile) */}
        {property.gallery.length > 0 && (
          <section className="container-x pt-10 sm:pt-14">
            <Gallery media={property.gallery} />
          </section>
        )}

        {/* About + highlights */}
        <section className="container-x grid grid-cols-1 gap-10 py-16 lg:grid-cols-[1.4fr_1fr] sm:py-20">
          <Reveal>
            <p className="eyebrow">About</p>
            <h2 className="h-fluid-2 mt-3">Your stay at {property.name}</h2>
            <p className="mt-5 text-pretty text-[clamp(1.05rem,2.2vw,1.2rem)] leading-relaxed text-ink/80">
              {property.about}
            </p>
            <div className="mt-7 flex flex-wrap items-center gap-3">
              <WhatsAppButton href={enquireHref} size="lg">
                Plan a visit
              </WhatsAppButton>

              {property.website ? (
                <a
                  href={property.website}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="inline-flex items-center justify-center gap-2 rounded-full border border-forest/30 bg-offwhite/70 px-6 py-3.5 text-base font-medium text-forest transition-colors hover:border-forest/60 hover:bg-offwhite"
                >
                  Visit their website
                </a>
              ) : (
                <button
                  type="button"
                  disabled
                  aria-disabled="true"
                  title="Website coming soon — we're still building it"
                  className="inline-flex cursor-not-allowed items-center justify-center gap-2 rounded-full border border-taupe/40 px-6 py-3.5 text-base font-medium text-muted/60"
                >
                  Visit their website
                  <span className="rounded-full bg-taupe/20 px-2 py-0.5 text-xs font-medium text-muted">
                    Coming soon
                  </span>
                </button>
              )}
            </div>
          </Reveal>

          {property.highlights.length > 0 && (
            <Reveal delay={120}>
              <div className="rounded-2xl border border-taupe/30 bg-offwhite p-7 shadow-soft">
                <h3 className="text-lg">Why you&apos;ll love it</h3>
                <ul className="mt-4 space-y-3">
                  {property.highlights.map((h) => (
                    <li key={h} className="flex gap-3 text-ink/80">
                      <span
                        aria-hidden="true"
                        className="mt-2 inline-block h-1.5 w-1.5 shrink-0 rounded-full bg-sage"
                      />
                      <span>{h}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </Reveal>
          )}
        </section>

        {/* Ways to visit (Day / Activities / Events) — shown before overnight stays */}
        {property.visitOptions.length > 0 && (
          <section className="container-x py-12">
            <SectionTitle
              eyebrow="Day · Activities · Events"
              title="Ways to visit"
              intro="Not staying the night? You can still park, eat and chill for the day, join an activity, or host a private event."
            />
            <div className="mt-10">
              <VisitOptions property={property} />
            </div>
          </section>
        )}

        {/* Stays — overnight options, shown last */}
        {property.units.length > 0 && (
          <section className="container-x py-12">
            <SectionTitle
              eyebrow="Stay · Overnight"
              title="Where you'll sleep"
              intro="Pick the room or house that fits your group — and whichever you choose, the pool is yours for the whole stay, whether it's a quiet morning swim or a lazy afternoon dip. Tap to enquire about any unit directly on WhatsApp."
            />
            <CurrencyNote className="mt-3 text-sm text-muted" />
            <div className="mt-8 space-y-6">
              {property.units.map((unit, i) => (
                <Reveal key={unit.id} delay={i * 80}>
                  <UnitCard property={property} unit={unit} />
                </Reveal>
              ))}
            </div>
          </section>
        )}

        {/* Closing CTA */}
        <section className="container-x py-12">
          <Reveal>
            <div className="overflow-hidden rounded-3xl bg-forest px-6 py-12 text-center shadow-lift sm:px-12 sm:py-14 lg:px-16">
              <h2 className="h-fluid-2 text-balance text-offwhite">
                Ready to plan your visit to {property.name}?
              </h2>
              <p className="mx-auto mt-3 max-w-xl text-pretty text-offwhite/80">
                Message us on WhatsApp and we&apos;ll help you choose dates, a room,
                or the right day-visit option for your group.
              </p>
              <div className="mt-8 flex justify-center">
                <WhatsAppButton
                  href={enquireHref}
                  size="lg"
                  variant="outline"
                  className="border-offwhite/40 bg-offwhite text-forest hover:bg-offwhite"
                >
                  Enquire on WhatsApp
                </WhatsAppButton>
              </div>
            </div>
          </Reveal>
        </section>

        {/* Keep exploring — a second page to visit (lowers bounce) */}
        {others.length > 0 && (
          <section className="container-x py-12">
            <div className="flex flex-wrap items-end justify-between gap-4">
              <div>
                <p className="eyebrow">Keep exploring</p>
                <h2 className="h-fluid-2 mt-3">More weekend escapes</h2>
              </div>
              <Link
                href="/"
                className="hidden items-center gap-1 text-sm font-medium text-forest hover:text-forest/80 sm:inline-flex"
              >
                View all escapes
                <span aria-hidden="true">→</span>
              </Link>
            </div>
            <div className="mt-8 grid grid-cols-1 gap-6 sm:grid-cols-2 lg:grid-cols-3">
              {others.map((p, i) => (
                <Reveal key={p.slug} delay={i * 90}>
                  <PropertyCard property={p} />
                </Reveal>
              ))}
            </div>
            <Link
              href="/"
              className="mt-6 inline-flex items-center gap-1 text-sm font-medium text-forest hover:text-forest/80 sm:hidden"
            >
              View all escapes
              <span aria-hidden="true">→</span>
            </Link>
          </section>
        )}
      </main>

      <SiteFooter />
      <StickyEnquire href={enquireHref} propertyName={property.name} />
    </>
  );
}
