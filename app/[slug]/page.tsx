import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { properties, getProperty } from "@/data/properties";
import { site } from "@/lib/site";
import { generalEnquiryLink } from "@/lib/whatsapp";
import SiteHeader from "@/components/SiteHeader";
import SiteFooter from "@/components/SiteFooter";
import Hero from "@/components/Hero";
import Gallery from "@/components/Gallery";
import UnitCard from "@/components/UnitCard";
import VisitOptions from "@/components/VisitOptions";
import WhatsAppButton from "@/components/WhatsAppButton";
import StickyEnquire from "@/components/StickyEnquire";
import Reveal from "@/components/Reveal";

type Params = { slug: string };

// Pre-render every property at build time (SSG) for Vercel.
export function generateStaticParams(): Params[] {
  return properties.map((p) => ({ slug: p.slug }));
}

export function generateMetadata({ params }: { params: Params }): Metadata {
  const property = getProperty(params.slug);
  if (!property) return {};

  const title = `${property.name} — ${property.location}`;
  const description = property.tagline;
  const url = `${site.url}/${property.slug}`;
  // Per-route OG image is generated by ./opengraph-image.tsx and resolved
  // automatically by Next via the file convention.

  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      type: "website",
      title: `${property.name} · ${site.name}`,
      description,
      url,
    },
    twitter: {
      card: "summary_large_image",
      title: `${property.name} · ${site.name}`,
      description,
    },
  };
}

function SectionTitle({
  eyebrow,
  title,
  intro,
}: {
  eyebrow: string;
  title: string;
  intro?: string;
}) {
  return (
    <Reveal>
      <p className="eyebrow">{eyebrow}</p>
      <h2 className="mt-3 text-3xl sm:text-4xl">{title}</h2>
      {intro && <p className="mt-3 max-w-2xl text-lg text-muted">{intro}</p>}
    </Reveal>
  );
}

export default function PropertyPage({ params }: { params: Params }) {
  const property = getProperty(params.slug);

  // Unknown slugs and not-yet-launched properties have no public page.
  if (!property || property.status !== "live") {
    notFound();
  }

  const enquireHref = generalEnquiryLink(property);

  return (
    <>
      <SiteHeader overlay />
      <Hero
        media={property.hero}
        name={property.name}
        tagline={property.tagline}
        location={property.location}
      />

      <main className="pb-28">
        {/* About + highlights */}
        <section className="container-x grid grid-cols-1 gap-10 py-16 lg:grid-cols-[1.4fr_1fr] sm:py-20">
          <Reveal>
            <p className="eyebrow">About</p>
            <h2 className="mt-3 text-3xl sm:text-4xl">
              Your stay at {property.name}
            </h2>
            <p className="mt-5 text-pretty text-lg leading-relaxed text-ink/80">
              {property.about}
            </p>
            <div className="mt-7">
              <WhatsAppButton href={enquireHref} size="lg">
                Plan a visit
              </WhatsAppButton>
            </div>
          </Reveal>

          {property.highlights.length > 0 && (
            <Reveal delay={120}>
              <div className="rounded-2xl border border-taupe/30 bg-offwhite p-7 shadow-soft">
                <h3 className="text-lg">Why you'll love it</h3>
                <ul className="mt-4 space-y-3">
                  {property.highlights.map((h) => (
                    <li key={h} className="flex gap-3 text-ink/80">
                      <span
                        aria-hidden="true"
                        className="mt-2 inline-block h-1.5 w-1.5 shrink-0 rounded-full bg-sage"
                      />
                      <span>{h}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </Reveal>
          )}
        </section>

        {/* Stays */}
        {property.units.length > 0 && (
          <section className="container-x py-12">
            <SectionTitle
              eyebrow="Stay · Overnight"
              title="Where you'll sleep"
              intro="Pick the room or house that fits your group. Tap to enquire about any unit directly on WhatsApp."
            />
            <div className="mt-8 space-y-6">
              {property.units.map((unit, i) => (
                <Reveal key={unit.id} delay={i * 80}>
                  <UnitCard property={property} unit={unit} />
                </Reveal>
              ))}
            </div>
          </section>
        )}

        {/* Ways to visit (Day / Events / Activities) */}
        {property.visitOptions.length > 0 && (
          <section className="container-x py-12">
            <SectionTitle
              eyebrow="Day · Events · Activities"
              title="Ways to visit"
              intro="Not staying the night? You can still park, eat and chill for the day, host a private event, or join an activity."
            />
            <div className="mt-10">
              <VisitOptions property={property} />
            </div>
          </section>
        )}

        {/* Gallery */}
        {property.gallery.length > 0 && (
          <section className="container-x py-12">
            <SectionTitle eyebrow="Gallery" title="A look around" />
            <div className="mt-8">
              <Gallery media={property.gallery} />
            </div>
          </section>
        )}

        {/* Closing CTA */}
        <section className="container-x py-12">
          <Reveal>
            <div className="overflow-hidden rounded-3xl bg-forest px-8 py-14 text-center shadow-lift sm:px-16">
              <h2 className="text-balance text-3xl text-offwhite sm:text-4xl">
                Ready to plan your visit to {property.name}?
              </h2>
              <p className="mx-auto mt-3 max-w-xl text-pretty text-offwhite/80">
                Message us on WhatsApp and we'll help you choose dates, a room,
                or the right day-visit option for your group.
              </p>
              <div className="mt-8 flex justify-center">
                <WhatsAppButton
                  href={enquireHref}
                  size="lg"
                  variant="outline"
                  className="border-offwhite/40 bg-offwhite text-forest hover:bg-offwhite"
                >
                  Enquire on WhatsApp
                </WhatsAppButton>
              </div>
            </div>
          </Reveal>
        </section>
      </main>

      <SiteFooter />
      <StickyEnquire href={enquireHref} propertyName={property.name} />
    </>
  );
}
